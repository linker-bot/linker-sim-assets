"""Generate coupled MJCFs for L6, O6, L20 Lite, L25 and L30.

    python -m linker_robot_assets.hand_coupling [--check-drift] [--hand l6]

Outputs retain source position actuators, dynamics, ratios and contacts. For
composed models, select mujoco.coupling_profile=hand_coupled in recipe.yaml.
"""

from __future__ import annotations

import argparse
import xml.etree.ElementTree as ET
from pathlib import Path

from . import asset_root
from .composer.compose import write_if_changed
from .composer.mjcf_profiles import (
    COUPLED_COMPONENTS,
    COUPLED_HANDS,
    apply_mujoco_options,
)
from .composer.schemas import ComponentMeta, MujocoOptions, SchemaError


def coupled_mjcf(component: Path, side: str) -> str:
    """Derive coupled/{left,right}.xml without duplicating authored dynamics."""
    meta = ComponentMeta.load(component / "meta.yaml")
    if meta.name not in COUPLED_COMPONENTS:
        raise SchemaError(f"No validated hand coupling profile for {meta.name}")
    variant = meta.variants[side]
    if not variant.mjcf:
        raise SchemaError(f"{meta.name}/{side} has no MJCF")
    source = component / variant.mjcf
    root = ET.parse(source).getroot()
    compiler = root.find("compiler")
    if compiler is None:
        raise SchemaError(f"{source}: missing compiler settings")
    compiler.set("meshdir", f"../{variant.meshdir}")
    root.set("model", f"{meta.name}_{side}_coupled")
    passive = [name.format(**variant.vars) for name in meta.mimic_joints]
    apply_mujoco_options(
        root, MujocoOptions(coupling_profile="hand_coupled"), [passive]
    )
    root.insert(
        0,
        ET.Comment(
            " Generated by python -m linker_robot_assets.hand_coupling; do not edit. "
            "Opt-in numerical profile, not hardware calibration. See docs/hand-mujoco-coupling.md. "
        ),
    )
    # The composer serializer rounds vector attributes to nine significant
    # figures. Preserve the authored axis values exactly in these standalone
    # variants: only solver settings and file locations should change.
    ET.indent(root, space="  ")
    return (
        '<?xml version="1.0" encoding="UTF-8"?>\n'
        + ET.tostring(root, encoding="unicode")
        + "\n"
    )


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--assets-root", type=Path, default=asset_root())
    parser.add_argument("--check-drift", action="store_true")
    parser.add_argument("--hand", choices=COUPLED_HANDS, action="append")
    args = parser.parse_args(argv)
    status = 0
    for name in args.hand or COUPLED_HANDS:
        component = args.assets_root / "components/hands" / f"linkerhand_{name}"
        for side in ("left", "right"):
            path = component / "coupled" / f"{side}.xml"
            expected = coupled_mjcf(component, side)
            if args.check_drift:
                if not path.is_file() or path.read_text() != expected:
                    print(
                        f"drift: {path}; re-run python -m linker_robot_assets.hand_coupling"
                    )
                    status = 1
                else:
                    print(f"[hand-coupling] {name}/{side}: no drift")
            else:
                write_if_changed(path, expected)
                print(f"[hand-coupling] {name}/{side}: written")
    return status


if __name__ == "__main__":
    raise SystemExit(main())
