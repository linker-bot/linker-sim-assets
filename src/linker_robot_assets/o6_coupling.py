"""Generate directly loadable O6 component MJCFs with stronger coupling.

    python -m linker_robot_assets.o6_coupling [--check-drift]

The outputs retain the source position actuators, joint dynamics and meshes.
For composed units/workstations, select the profile in recipe.yaml instead.
"""

from __future__ import annotations

import argparse
import xml.etree.ElementTree as ET
from pathlib import Path

from . import asset_root
from .composer.compose import write_if_changed
from .composer.determinism import serialize
from .composer.mjcf_profiles import apply_mujoco_options
from .composer.schemas import ComponentMeta, MujocoOptions


def coupled_mjcf(component: Path, side: str) -> str:
    """Deterministically derive coupled/{left,right}.xml from the component."""
    meta = ComponentMeta.load(component / "meta.yaml")
    variant = meta.variants[side]
    root = ET.parse(component / variant.mjcf).getroot()
    # Outputs live one directory below the original component MJCFs.
    compiler = root.find("compiler")
    compiler.set("meshdir", f"../{variant.meshdir}")
    root.set("model", f"linkerhand_o6_{side}_coupled")
    passive = [name.format(**variant.vars) for name in meta.mimic_joints]
    apply_mujoco_options(root, MujocoOptions(coupling_profile="o6_coupled"), [passive])
    root.insert(
        0,
        ET.Comment(
            " Generated by python -m linker_robot_assets.o6_coupling; do not edit. "
            "Opt-in numerical profile, not hardware calibration. See docs/o6-mujoco-coupling.md. "
        ),
    )
    return serialize(root)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--assets-root", type=Path, default=asset_root())
    parser.add_argument("--check-drift", action="store_true")
    args = parser.parse_args(argv)
    component = args.assets_root / "components/hands/linkerhand_o6"
    status = 0
    for side in ("left", "right"):
        path = component / "coupled" / f"{side}.xml"
        expected = coupled_mjcf(component, side)
        if args.check_drift:
            if not path.is_file() or path.read_text() != expected:
                print(
                    f"drift: {path}; re-run python -m linker_robot_assets.o6_coupling"
                )
                status = 1
            else:
                print(f"[o6-coupling] {side}: no drift")
        else:
            write_if_changed(path, expected)
            print(f"[o6-coupling] {side}: written")
    return status


if __name__ == "__main__":
    raise SystemExit(main())
